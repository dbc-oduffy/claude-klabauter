"""
coordinator_core.ops.gate_dimension_latency — the "latency" dimension for
`gate.validate_invocable` (C7,
docs/plans/2026-07-20-merge-gate-dod-engine-enforced.md § C7).

Purpose: plug a real `latency` check into `gate_validate_invocable`'s
dimension seam via `register_dimension("latency", ...)` at import time — the
exact self-registration shape `register_op` uses elsewhere in this package
(see `gate_validate_invocable`'s own module docstring, "Dimension seam").
This module never edits `gate_validate_invocable.py`; it plugs into the seam
that module already exposes.

**Reference, never rebuild** (hard anti-scope, C7): this module reads
`coordinator_core.benchmarks.gate::evaluate`, `budget.py`, and the persisted
`baseline_store` — it does not re-derive gate-verdict math, does not
re-implement the budget manifest resolver, and — load-bearing — it never
calls `coordinator_core.benchmarks.harness.run()` (which spawns a real
subprocess per sample). A COMPUTE_ONLY dimension check that shells a
benchmark subprocess sweep on every gate call would itself blow a
COMPUTE_ONLY latency budget; this dimension is a pure read over
already-persisted `ConformanceRecord` history
(`coordinator_core/benchmarks/baselines/baseline.jsonl`), never a live
measurement. See `docs/wiki/latency-benchmark-harness.md` for the harness
this module reads from (gate-verdict semantics: `(observed_statistic,
target_ms, tolerance, sample_count, min_gating_sample_count)`; below
`min_gating_sample_count` the gate always emits `advisory`; `floor_delta_ms`
is signed/nullable/advisory-only and never gating — this module does not
touch `floor_delta_ms` at all).

**Self-exclusion (hard requirement, C7).** `gate.validate_invocable` is
itself classified COMPUTE_ONLY, and the manifest's COMPUTE_ONLY default is
`target_ms: 70` — but that op shells mypy, ruff, interrogate, a
`pytest --cov` run, and diff-cover, three orders of magnitude outside that
band. This module's own module file and its test file, plus
`gate_validate_invocable.py` and its test file, are hardcoded into
`_SELF_EXCLUDED_PATHS` and stripped from the path set before any op mapping
happens — a red COMPUTE_ONLY latency reading on the validator is a
budget-override request routed to qsub-01 (never a silent hand-edit of
`budget-manifest.json`), so it must never even reach that state via this
dimension. See
state/lessons/2026-08-07-a-gate-that-measures-a-corpus-must-not-l-dec459bb6300.yaml
("a stated principle protects the file that states it, not the next one") —
the principle is enforced here, for THIS file, not merely stated.

**Loud re-entrancy sentinel.** `_REENTRANCY_GUARD` is a module-level flag
set for the duration of one `_check_latency` call. A nested call while the
guard is set (this dimension check somehow re-entering itself — e.g. a
future consumer routing `gate.validate_invocable` through the very op it is
scoping) raises `LatencyDimensionReentrancyError` LOUDLY rather than
silently returning a vacuous PASS/UNAVAILABLE. `_run_dimension()` in
`gate_validate_invocable.py` converts any raised exception into `ERROR` —
a loud ERROR the caller can see, never a silent pass-through, per the
lesson's "a silent guard against recursion makes the gate pass vacuously,
which is worse than the recursion it guards against."

Op → module-path mapping: read from `.github/op-inventory.json` (the C6
landed "one shared ported-ops paths fragment", generated by
`scripts/gen_ported_ops_fragment.py`) — this module does not maintain its
own parallel op↔path table.

Spec backlink: docs/plans/2026-07-20-merge-gate-dod-engine-enforced.md § C7
"""

from __future__ import annotations

import contextvars
import json
from pathlib import Path
from typing import Optional

from coordinator_core.authz.classification import OpClass
from coordinator_core.benchmarks import baseline_store
from coordinator_core.benchmarks import budget as budget_mod
from coordinator_core.benchmarks import gate as gate_mod
from coordinator_core.ops.gate_validate_invocable import (
    DimensionResult,
    Verdict,
    register_dimension,
)

# ---------------------------------------------------------------------------
# Self-exclusion — never measure the validator or this dimension's own files.
# Paths are repo-root-relative with forward slashes, matching the shape
# `.github/ported-ops-paths.txt` / `op-inventory.json` and typical git
# changed-file output use; `_normalize_path` below also accepts backslash
# (Windows) separators from a caller.
# ---------------------------------------------------------------------------
_SELF_EXCLUDED_PATHS: frozenset[str] = frozenset(
    {
        "coordinator_core/ops/gate_validate_invocable.py",
        "coordinator_core/ops/tests/test_gate_validate_invocable.py",
        "coordinator_core/ops/gate_dimension_latency.py",
        "coordinator_core/ops/tests/test_gate_dimension_latency.py",
    }
)

_OP_INVENTORY_PATH = Path(__file__).parent.parent.parent / ".github" / "op-inventory.json"


class LatencyDimensionReentrancyError(RuntimeError):
    """Raised loudly on a detected re-entrant call into the latency check.

    Never caught within this module — `_run_dimension()` (the caller, in
    `gate_validate_invocable.py`) converts it into a visible `Verdict.ERROR`,
    which is the point: a silent recursion guard would make the gate pass
    vacuously (see module docstring, "Loud re-entrancy sentinel").
    """


_REENTRANCY_GUARD: contextvars.ContextVar[bool] = contextvars.ContextVar(
    "_gate_dimension_latency_reentrancy_guard", default=False
)
"""Per-context re-entrancy flag — set for the duration of one
`_check_latency` call.

`contextvars.ContextVar` rather than a bare module bool (C8,
docs/plans/2026-08-15-warm-engine-retires-the-per-invocation-cold-start.md):
under a warm engine, `_check_latency` is no longer guaranteed single-threaded
per process — two UNRELATED concurrent dispatches (two sessions gating two
different commits at once) must not trip each other's sentinel, which a bare
module bool did (the characterization test this fix flips,
`coordinator_core/warm/tests/test_process_global_characterization.py`
Site 5). A genuine RE-ENTRANT call — this dimension check somehow calling
back into itself within the SAME dispatch's Task/thread Context — still sees
the flag set and still raises `LatencyDimensionReentrancyError`: a ContextVar
read/write is scoped to the current Context, and a synchronous nested call
runs in that same Context, so within-context re-entry detection is
unaffected. Only cross-context (i.e. cross-dispatch) false trips are
removed."""


def _normalize_path(raw: str) -> str:
    """Normalize a changed-file path to forward-slash, repo-root-relative
    form for comparison against `_SELF_EXCLUDED_PATHS` / the inventory.

    # Review: coordinator:code-reviewer wsc-B-dimensions — a bare
    # `.lstrip("./")` strips any run of `.`/`/` characters, not the literal
    # `"./"` prefix; strip the literal prefix once instead.
    """
    normalized = raw.replace("\\", "/")
    if normalized.startswith("./"):
        normalized = normalized[2:]
    return normalized


def _load_op_inventory() -> list[dict]:
    """Load `.github/op-inventory.json` (C6's landed fragment). Returns an
    empty list if the file is missing rather than raising — an absent
    inventory means "no ops mapped," handled as UNAVAILABLE by the caller,
    not a hard failure of the whole dimension.

    A malformed (present but not valid JSON) inventory still fails closed —
    `_run_dimension`'s catch-all still converts it to `Verdict.ERROR` — but
    is re-raised with a legible message naming the file, mirroring
    `gate_dimension_docstrings._load_fail_under`'s degrade-with-a-reason
    shape rather than surfacing a bare `json.JSONDecodeError` traceback.
    # Review: coordinator:code-reviewer wsc-B-dimensions — message-legibility
    # parity with the docstrings dimension's malformed-file handling.
    """
    if not _OP_INVENTORY_PATH.exists():
        return []
    with _OP_INVENTORY_PATH.open("r", encoding="utf-8") as fh:
        try:
            return json.load(fh)
        except json.JSONDecodeError as exc:
            raise ValueError(f"{_OP_INVENTORY_PATH} is malformed JSON: {exc}") from exc


def _map_paths_to_ops(
    changed_files: list[str], inventory: Optional[list[dict]] = None
) -> dict[str, str]:
    """Return {op_key: module_path} for every changed file that maps to a
    registered op's module in the inventory, after self-exclusion.

    A file with no matching inventory entry (not an op module — e.g. a doc,
    a test helper, a non-op library module) is silently not included; it is
    not this dimension's concern (mirrors the other dimensions' path-scoped
    convention of only asserting over the ported-ops path set).

    `inventory` may be passed in by a caller that already loaded it once per
    gate run (see `_check_latency`) to avoid re-reading
    `.github/op-inventory.json` from disk once per mapped op; defaults to a
    fresh load for callers (e.g. tests) that invoke this directly."""
    normalized_changed = {_normalize_path(f) for f in changed_files}
    normalized_changed -= _SELF_EXCLUDED_PATHS

    if inventory is None:
        inventory = _load_op_inventory()
    mapping: dict[str, str] = {}
    for entry in inventory:
        module_path = entry.get("module_path")
        op_key = entry.get("op_key")
        if not module_path or not op_key:
            continue
        if _normalize_path(module_path) in normalized_changed:
            mapping[op_key] = module_path
    return mapping


def _op_class_for(op_key: str, inventory: Optional[list[dict]] = None) -> Optional[OpClass]:
    """Resolve an op's OpClass from the inventory's own classification
    field — kept local to this module rather than importing
    `coordinator_core.authz.classification.OP_CLASSIFICATION` and risking a
    drift between the two; the inventory is the C6 single source of truth
    for path-scoped dimensions.

    `inventory` may be passed in by a caller that already loaded it once per
    gate run (see `_check_latency`); defaults to a fresh load for callers
    (e.g. tests) that invoke this directly.
    # Review: coordinator:code-reviewer wsc-B-dimensions — avoid re-reading
    # op-inventory.json from disk once per mapped op in `_check_latency`.
    """
    if inventory is None:
        inventory = _load_op_inventory()
    for entry in inventory:
        if entry.get("op_key") == op_key:
            classification = entry.get("classification")
            if classification is None:
                return None
            return OpClass[classification]
    return None


def _latest_record_for(op_key: str):
    """Return the most recently appended `ConformanceRecord` for `op_key`
    across the whole baseline store, or None if it has never been
    benchmarked. `baseline_store.query` yields in append order and does not
    collapse history itself (its own documented contract) — this is the
    "select the last matching line yourself" step its docstring calls for."""
    latest = None
    for record in baseline_store.query(op=op_key):
        latest = record
    return latest


_HIGH_LOAD_LIVE_SESSIONS_THRESHOLD = 45
"""C1's measured bands: live_sessions < 20 / 20-45 / > 45. Only the ">45"
boundary matters here — a record measured above it is in a band C1 never
benchmarked, so gate.py's raw 'fail' cannot be trusted standalone (see
`_verdict_for_op`'s load-skew downgrade)."""


def _verdict_for_op(op_key: str, op_class: Optional[OpClass]) -> tuple[str, str]:
    """Return (sub_verdict, detail) for one mapped op.

    sub_verdict is one of: "pass", "fail", "advisory", "unavailable" — this
    module's own vocabulary, folded into the aggregate `Verdict` by
    `_check_latency` below (gate.py's own tri-state ('pass'/'fail'/
    'advisory') is reused verbatim for the COMPUTE_ONLY case; MUTATING and
    "never benchmarked" are this module's additions, both non-gating).

    Load-skew downgrade (C4, single-record rule): a raw gate.py 'fail' is
    downgraded to 'advisory' when THIS record's own ambient band — read off
    its own `ambient_before.live_sessions` (the in-process sample taken at
    measurement start, closest to the timed window) — is unknown (null) or
    is the high-load band C1 never measured (`live_sessions > 45`). There is
    no baseline record to compare against here; this reads only the one
    record already fetched above, per DR-296's fail-quiet swimlane. gate.py
    itself is not touched — the model lives in this caller, not in the
    verdict arithmetic (see module docstring, C4).
    """
    if op_class is OpClass.MUTATING:
        return (
            "advisory",
            f"{op_key}: MUTATING op, budget provisional — advisory-only "
            "until qsub-01's MUTATING budgets land (C7 anti-scope)",
        )

    if op_class is None:
        return (
            "unavailable",
            f"{op_key}: classification absent or unrecognized in "
            "op-inventory.json — gate does not know, so it does not guess",
        )

    record = _latest_record_for(op_key)
    if record is None:
        return ("unavailable", f"{op_key}: no benchmark history in baseline store")

    manifest = budget_mod.load_manifest()
    min_gating_sample_count = manifest["min_gating_sample_count"]
    sub_verdict = gate_mod.evaluate(
        observed_statistic=record.gating_statistic_value,
        target_ms=record.target_ms,
        tolerance=record.tolerance,
        sample_count=record.sample_count,
        min_gating_sample_count=min_gating_sample_count,
    )

    load_skew_reason: Optional[str] = None
    if sub_verdict == "fail":
        ambient_before = record.ambient_before or {}
        live_sessions = ambient_before.get("live_sessions")
        if live_sessions is None:
            load_skew_reason = "ambient live_sessions unknown at measurement time"
        elif live_sessions > _HIGH_LOAD_LIVE_SESSIONS_THRESHOLD:
            load_skew_reason = (
                f"ambient live_sessions={live_sessions} is above the high-load "
                f"band ({_HIGH_LOAD_LIVE_SESSIONS_THRESHOLD}) C1 never measured"
            )
        if load_skew_reason is not None:
            sub_verdict = "advisory"

    detail = (
        f"{op_key}: {sub_verdict} ({record.gating_statistic}="
        f"{record.gating_statistic_value:.2f}ms vs target={record.target_ms}ms, "
        f"n={record.sample_count}, code_sha={record.code_sha[:12]})"
    )
    if load_skew_reason is not None:
        detail += f" [downgraded from fail: {load_skew_reason}]"
    return (sub_verdict, detail)


def _check_latency(
    changed_files: list[str], diff_base: Optional[str], repo_root: Optional[Path]
) -> DimensionResult:
    """The registered `latency` DimensionCheck (C7).

    Maps `changed_files` to ops via the op-inventory fragment (after
    self-exclusion), reads each mapped op's latest persisted
    `ConformanceRecord`, and evaluates it via `gate.evaluate` — never runs a
    fresh benchmark subprocess sweep (see module docstring). COMPUTE_ONLY
    ops gate for real (`fail` sub-verdicts flip the dimension to FAIL);
    MUTATING ops are always advisory (never flip the dimension); an op with
    no benchmark history yet is `unavailable` for that op alone (still
    never gating).

    Overall dimension verdict:
      - FAIL     if any mapped COMPUTE_ONLY op's latest record reads "fail".
      - PASS     if at least one mapped COMPUTE_ONLY op read "pass"/
                 "advisory" and none read "fail".
      - UNAVAILABLE if no changed file mapped to any op at all, or every
                 mapped op's record was "unavailable"/every mapped op is
                 MUTATING (nothing gating to report).
    """
    if _REENTRANCY_GUARD.get():
        raise LatencyDimensionReentrancyError(
            "latency dimension check re-entered itself — refusing to "
            "silently pass; see gate_dimension_latency module docstring "
            "'Loud re-entrancy sentinel'"
        )
    token = _REENTRANCY_GUARD.set(True)
    try:
        inventory = _load_op_inventory()
        op_map = _map_paths_to_ops(changed_files, inventory=inventory)
        if not op_map:
            return DimensionResult(
                dimension="latency",
                verdict=Verdict.UNAVAILABLE,
                detail="no changed file maps to a benchmarked op",
            )

        details: list[str] = []
        any_gating_result = False
        any_fail = False
        for op_key in sorted(op_map):
            op_class = _op_class_for(op_key, inventory=inventory)
            sub_verdict, detail = _verdict_for_op(op_key, op_class)
            details.append(detail)
            if sub_verdict in ("pass", "fail"):
                any_gating_result = True
            if sub_verdict == "fail":
                any_fail = True

        joined_detail = "; ".join(details)
        if any_fail:
            return DimensionResult(dimension="latency", verdict=Verdict.FAIL, detail=joined_detail)
        if any_gating_result:
            return DimensionResult(dimension="latency", verdict=Verdict.PASS, detail=joined_detail)
        return DimensionResult(
            dimension="latency", verdict=Verdict.UNAVAILABLE, detail=joined_detail
        )
    finally:
        _REENTRANCY_GUARD.reset(token)


register_dimension("latency", _check_latency)
