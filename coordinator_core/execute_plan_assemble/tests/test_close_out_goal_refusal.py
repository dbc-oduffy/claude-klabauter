def _run_git(args: list[str], cwd: Path) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["git", *args], cwd=str(cwd), capture_output=True, text=True, check=True, **no_console_creationflags()
    )


def _init_repo(root: Path) -> None:
    _run_git(["init", "-q"], root)
    _run_git(["config", "user.email", "t@t"], root)
    _run_git(["config", "user.name", "test"], root)


def _head_sha(root: Path) -> str:
    return _run_git(["rev-parse", "HEAD"], root).stdout.strip()


def _run_close_out(
    monkeypatch: pytest.MonkeyPatch, root: Path, plan_rel: str, *, dry_run: bool = False
) -> tuple[int, dict]:
    monkeypatch.chdir(root)
    return coas.close_out_and_stamp(plan_rel, repo_root=root, dry_run=dry_run)


_PLAN_TEMPLATE = """---
title: "Fixture plan — goal-falsifier gate"
created: 2026-08-27
author: test-fixture
status: {status}
branch: "work/test-fixture/2026-08-27"
plan_id: "pln-fixture-goal-gate-000001"
deliverable_id: "dlv-fixture-goal-gate-000001"
{goal_frontmatter}---

# Fixture plan — goal-falsifier gate

## Tasks

```yaml plan-tasks
{rows}
```
"""


def _prime_exit_criterion_block(
    *,
    derived_from: str = "state/sizings/2026-08-27-fixture-sizing.yaml",
    baseline_ref: str,
    exit_criterion_met: Optional[str],
    status_override: Optional[str] = None,
) -> str:
    """Renders the `prime_exit_criterion:`/`exit_criterion_met:` frontmatter
    block this file's fixture plans embed. `exit_criterion_met` is a raw
    YAML block (pre-indented) or `None` to omit the field entirely (arm 2's
    absent case). `status_override`, when given, is a raw YAML block for
    the `status_override_*` trio (AC19)."""
    lines = [
        "prime_exit_criterion:",
        "  statement: The fixture surface behaves as claimed.",
        f"  derived_from: {derived_from}",
        "  falsifier:",
        "    how: read the fixture surface",
        "    baseline_output: 'wrong'",
        f"    baseline_ref: {baseline_ref}",
        "    expected_when_true: 'right'",
    ]
    if exit_criterion_met is not None:
        lines.append("exit_criterion_met:")
        lines.append(exit_criterion_met)
    if status_override is not None:
        lines.append(status_override)
    return "\n".join(lines) + "\n"


_SHIPPED_ROW = (
    "- id: C1\n"
    "  title: Only chunk\n"
    "  change_kind: code-edit\n"
    "  surface: fixture.py\n"
    "  deferred: false\n"
    "  disposition: coded\n"
    "  disposition_ref: {sha}\n"
    "  disposition_detail: 'landed'\n"
    "  body: |\n"
    "    The only chunk.\n"
)


def _seed_goal_plan(
    root: Path,
    *,
    goal_frontmatter: str,
    shipping_sha: str,
    status: str = "executing",
    dest_name: str = "plan.md",
) -> Path:
    text = _PLAN_TEMPLATE.format(
        status=status,
        goal_frontmatter=goal_frontmatter,
        rows=_SHIPPED_ROW.format(sha=shipping_sha),
    )
    dest = root / dest_name
    dest.write_text(text, encoding="utf-8")
    _run_git(["add", dest_name], root)
    # The default `derived_from` every `_prime_exit_criterion_block` call
    # points at (`state/sizings/2026-08-27-fixture-sizing.yaml`) must
    # resolve for tests that are not themselves exercising arm 5's own
    # unresolvable case -- seeded here so every OTHER test in this file
    # never trips arm 5 by accident.
    sizing_rel = "state/sizings/2026-08-27-fixture-sizing.yaml"
    sizing_path = root / sizing_rel
    if not sizing_path.is_file():
        sizing_path.parent.mkdir(parents=True, exist_ok=True)
        sizing_path.write_text("estimate:\n  tshirt: S\n", encoding="utf-8")
        _run_git(["add", sizing_rel], root)
    _run_git(["commit", "-q", "-m", "seed"], root)
    return dest


def _land_the_shipping_chunk(root: Path) -> str:
    """Lands a real commit this repo's own history can verify as an
    ancestor of `HEAD` -- the sha every fixture plan's `disposition_ref`
    (spine evidence) AND, in the passing-baseline case, `falsifier.
    baseline_ref` both point at."""
    (root / "fixture.py").write_text("v1", encoding="utf-8")
    _run_git(["add", "fixture.py"], root)
    _run_git(["commit", "-q", "-m", "land the only chunk"], root)
    return _head_sha(root)


def _make_non_ancestor_commit(root: Path) -> str:
    head_tree = _run_git(["rev-parse", "HEAD^{tree}"], root).stdout.strip()
    result = _run_git(
        ["commit-tree", head_tree, "-m", "unreachable commit"], root
    )
    return result.stdout.strip()


def _asserted_pass_block() -> str:
    return (
        "  asserted: true\n"
        "  falsifier_output: 'right'\n"
        "  falsifier_verdict: pass\n"
        "  prose: matches the stated pass condition\n"
    )


def _asserted_false_block() -> str:
    return "  asserted: false\n  reason: the surface was removed by the work\n"


def _asserted_true_verdict_fail_block() -> str:
    return (
        "  asserted: true\n"
        "  falsifier_output: 'still wrong'\n"
        "  falsifier_verdict: fail\n"
    )


def _status_override_block(body_sha: str, *, current: bool = True) -> str:
    reason = (
        f"body_sha={body_sha}: surface deleted by the work, cannot re-observe"
        if current
        else "body_sha=0000000000000000000000000000000000000000: stale override"
    )
    return (
        "status_override_by: test-override-session\n"
        f"status_override_reason: '{reason}'\n"
        "status_override_at: '2026-08-27T00:00:00Z'\n"
    )


