class TestFalsifierBlockDetectionIsTotal:
    """AC7: absent, null, non-object, structurally incomplete, and
    unparseable falsifier shapes ALL route to `None` (arm 1) and none of
    them raises."""

    def test_prime_exit_criterion_not_a_dict(self):
        assert coas._falsifier_block("not a dict") is None
        assert coas._falsifier_block(None) is None
        assert coas._falsifier_block([1, 2, 3]) is None

    def test_falsifier_absent(self):
        assert coas._falsifier_block({"statement": "x", "derived_from": "y"}) is None

