"""Self-resolving corpus-guard pre-commit hook body and the forwarder-stub predicate.

`hook_body` is a POSIX sh hook that finds the engine's authored
`pre_commit_corpus_artifact_guard.py` itself and execs it; it never forwards through a
`coordinator/bin` stub (a stub copied into `.git/hooks` has no `lib/` and dies on import).
Zero subprocess spawns here.
"""
from __future__ import annotations

import os
from typing import Optional

from coordinator_core.py_probe_sh import python_probe_lines

STAMP = "# coordinator corpus-guard pre-commit (generated by coordinator_core.git.corpus_guard_hook)"

_GUARD_REL = "coordinator/bin/pre_commit_corpus_artifact_guard.py"


def is_forwarder_stub(text: str) -> bool:
    """True for a copied `coordinator/bin` forwarder stub (same test as publish.py::_is_engine_forward_stub)."""
    return "_engine_forward" in text and "Edit in claude-klabauter" in text


def candidate_engine_roots() -> list[str]:
    """Existing engine roots to bake: registry `repos.claude_klabauter`, then the published mirror.

    Forward slashes, de-duplicated, existing directories only.
    """
    raw: list[Optional[str]] = []
    try:
        from coordinator_core.machine_resolver import merged_flat_registry

        raw.append(str(merged_flat_registry().get("repos.claude_klabauter") or "").strip() or None)
    except Exception:
        raw.append(None)
    try:
        from coordinator_core.engine_root import published_engine_mirror_path

        raw.append(published_engine_mirror_path())
    except Exception:
        raw.append(None)

    roots: list[str] = []
    for r in raw:
        if not r or not os.path.isdir(r):
            continue
        norm = r.replace("\\", "/").rstrip("/") or "/"
        if norm not in roots:
            roots.append(norm)
    return roots


def _sq(value: str) -> str:
    return "'" + value.replace("'", "'\\''") + "'"


def hook_body(roots: Optional[list[str]] = None) -> str:
    """POSIX sh pre-commit hook: exec the engine guard from `$COORDINATOR_ENGINE_ROOT`, then baked roots.

    `roots=None` bakes `candidate_engine_roots()`. No root found exits 1 with a one-line
    remedy: a guard that silently passes is the defect class. Raises ValueError if the
    output would itself be a forwarder stub.
    """
    baked = candidate_engine_roots() if roots is None else [r.replace("\\", "/") for r in roots]
    root_list = " ".join(['"${COORDINATOR_ENGINE_ROOT:-}"'] + [_sq(r) for r in baked])
    lines = [
        "#!/bin/sh",
        STAMP,
        python_probe_lines("_py"),
        'if [ -z "$_py" ]; then',
        '  echo "pre-commit: no python3/python/py on PATH; the corpus guard cannot run" >&2',
        "  exit 1",
        "fi",
        f"for _root in {root_list}; do",
        '  [ -n "$_root" ] || continue',
        f'  _guard="$_root/{_GUARD_REL}"',
        '  if [ -f "$_guard" ]; then',
        '    exec "$_py" "$_guard" "$@"',
        "  fi",
        "done",
        'echo "pre-commit: engine not found; set COORDINATOR_ENGINE_ROOT or run pre_commit_corpus_artifact_guard --install-hook in this repo" >&2',
        "exit 1",
        "",
    ]
    body = "\n".join(lines)
    if is_forwarder_stub(body):
        raise ValueError("generated hook body is a forwarder stub")
    return body
