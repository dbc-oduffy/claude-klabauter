"""Authoring-time generator for the sectioned guard-routes folder.

``python -m coordinator_core.guard_routes.assemble --write`` regenerates
``docs/reference/guard-routes/`` (section files plus a README index);
``--check`` exits non-zero on any byte difference and prints the differing
file names. No runtime path imports this module: a deny only computes
``gr:<guard>`` from keys.py.
"""
from __future__ import annotations

import argparse
import ast
import dis
import re
import sys
import types
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from typing import Dict, FrozenSet, List, Optional, Set, Tuple

from coordinator_core.atomic_replace import atomic_write_bytes
from coordinator_core.guard_routes.keys import ROUTES_DIR, ROUTES_INDEX, route_key

_REPO_ROOT = Path(__file__).resolve().parents[2]
_BASH_PKG = "coordinator_core.bash_guards"
_SHARED_CHECKS = _BASH_PKG + ".dispatch_checks"
_MAX_SECTION_LINES = 300
_ENV_PREFIX = "COORDINATOR"

_README_HEADER = (
    "# Guard routes\n"
    "\n"
    "Generated by `python -m coordinator_core.guard_routes.assemble --write` from the live guard\n"
    "rosters. Do not hand-edit.\n"
    "\n"
    "A denial names a key, `gr:<guard-name>`. To find its section, grep this folder:\n"
    "`grep -rn 'gr:<guard-name> |' .`\n"
    "\n"
    "Channel mechanics (sentinels, env vars, in-session unlock) are in\n"
    "`guard-override-keys.md`, one directory up.\n"
)


@dataclass(frozen=True)
class _Mod:
    dotted: str
    tree: ast.Module
    consts: Dict[str, str]
    imports: Dict[str, Tuple[str, Optional[str]]]


@lru_cache(maxsize=None)
def _load_mod(dotted: str) -> Optional[_Mod]:
    base = _REPO_ROOT / dotted.replace(".", "/")
    path = base.with_suffix(".py")
    if not path.is_file():
        path = base / "__init__.py"
        if not path.is_file():
            return None
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"))
    except (OSError, SyntaxError, UnicodeDecodeError):
        return None
    consts: Dict[str, str] = {}
    imports: Dict[str, Tuple[str, Optional[str]]] = {}
    for _ in range(2):
        for node in ast.walk(tree):
            target, value = None, None
            if isinstance(node, ast.Assign) and len(node.targets) == 1:
                target, value = node.targets[0], node.value
            elif isinstance(node, ast.AnnAssign) and node.value is not None:
                target, value = node.target, node.value
            if not isinstance(target, ast.Name) or value is None:
                continue
            if isinstance(value, ast.Constant) and isinstance(value.value, str):
                consts[target.id] = value.value
            elif isinstance(value, ast.Name) and value.id in consts:
                consts[target.id] = consts[value.id]
    parts = dotted.split(".")
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for a in node.names:
                imports[a.asname or a.name.split(".")[0]] = (a.name if a.asname else a.name.split(".")[0], None)
        elif isinstance(node, ast.ImportFrom):
            if node.level:
                base_parts = parts[: -node.level] + (node.module.split(".") if node.module else [])
                module = ".".join(base_parts)
            else:
                module = node.module or ""
            for a in node.names:
                imports[a.asname or a.name] = (module, a.name)
    return _Mod(dotted, tree, consts, imports)


def _resolve(expr: ast.AST, mod: _Mod) -> Optional[str]:
    if isinstance(expr, ast.Constant) and isinstance(expr.value, str):
        return expr.value
    if isinstance(expr, ast.Name):
        if expr.id in mod.consts:
            return mod.consts[expr.id]
        origin = mod.imports.get(expr.id)
        if origin and origin[1]:
            other = _load_mod(origin[0])
            if other is not None:
                return other.consts.get(origin[1])
        return None
    if isinstance(expr, ast.Attribute) and isinstance(expr.value, ast.Name):
        origin = mod.imports.get(expr.value.id)
        if origin:
            dotted = origin[0] if origin[1] is None else origin[0] + "." + origin[1]
            other = _load_mod(dotted)
            if other is not None:
                return other.consts.get(expr.attr)
    return None


def _call_name(node: ast.Call) -> str:
    if isinstance(node.func, ast.Name):
        return node.func.id
    if isinstance(node.func, ast.Attribute):
        return node.func.attr
    return ""


_OVERRIDE_FAMILY_RE = re.compile(r"COORDINATOR_(?:OVERRIDE|ALLOW|DISABLE|PROBE)_[A-Z0-9_]+")


def _env_vars(root: ast.AST, mod: _Mod) -> Set[str]:
    """Override env vars in ``root``: constant-resolved first args of ``operator_override_note`` /
    ``_override`` and ``Override(env_var=...)`` values, plus any string constant that is itself an
    override-family key."""
    found: Set[str] = set()
    for node in ast.walk(root):
        if isinstance(node, ast.Constant) and isinstance(node.value, str):
            if _OVERRIDE_FAMILY_RE.fullmatch(node.value):
                found.add(node.value)
            continue
        if not isinstance(node, ast.Call):
            continue
        name = _call_name(node)
        arg: Optional[ast.AST] = None
        if name in ("operator_override_note", "_override"):
            arg = node.args[0] if node.args else None
        if arg is None and name in ("operator_override_note", "Override"):
            arg = next((k.value for k in node.keywords if k.arg == "env_var"), None)
        if arg is None:
            continue
        value = _resolve(arg, mod)
        if value and value.startswith(_ENV_PREFIX):
            found.add(value)
    return found


def _first_line(doc: Optional[str]) -> str:
    """First paragraph of a docstring, whitespace-collapsed, module prefix stripped, capped at 160 chars."""
    paragraph = (doc or "").strip().split("\n\n")[0]
    text = re.sub(r"^[\w.]+\s+(?:--|—|–)\s+", "", " ".join(paragraph.split()))
    if len(text) > 160:
        text = text[:160].rsplit(" ", 1)[0] + " ..."
    return text


@lru_cache(maxsize=1)
def _shared_universe() -> Dict[str, List[Tuple[_Mod, ast.FunctionDef]]]:
    """Every function def in dispatch_checks and its ``_dc_*`` siblings, by name."""
    index: Dict[str, List[Tuple[_Mod, ast.FunctionDef]]] = {}
    names = ["dispatch_checks"] + sorted(
        p.stem for p in (_REPO_ROOT / "coordinator_core/bash_guards").glob("_dc_*.py")
    )
    for stem in names:
        mod = _load_mod(_BASH_PKG + "." + stem)
        if mod is None:
            continue
        for node in ast.walk(mod.tree):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                index.setdefault(node.name, []).append((mod, node))
    return index


def _closure_env(check_names: List[str]) -> Tuple[Set[str], str]:
    """Env vars reachable from the named check functions through calls to shared-module functions."""
    index = _shared_universe()
    seen: Set[str] = set()
    queue = [n for n in check_names if n in index]
    env: Set[str] = set()
    doc = ""
    shared = _load_mod(_SHARED_CHECKS)
    for name in check_names:
        origin = shared.imports.get(name) if shared is not None else None
        if origin and origin[0] != _SHARED_CHECKS and origin[0].startswith(_BASH_PKG + "."):
            if origin[0].rsplit(".", 1)[-1].startswith("_dc_"):
                continue
            e, d = _scan_module(origin[0])
            env |= e
            doc = doc or d
    while queue:
        name = queue.pop(0)
        if name in seen:
            continue
        seen.add(name)
        for mod, fdef in index[name]:
            env |= _env_vars(fdef, mod)
            if not doc and name in check_names:
                doc = _first_line(ast.get_docstring(fdef))
            for node in ast.walk(fdef):
                for target in _guard_module_refs(node, mod):
                    e, d = _scan_module(target)
                    env |= e
                    doc = doc or d
                if isinstance(node, ast.Call):
                    callee = _call_name(node)
                    if callee in index and callee not in seen:
                        queue.append(callee)
    return env, doc


def _guard_module_refs(node: ast.AST, mod: _Mod) -> List[str]:
    """Public guard modules a shared-module function reaches: a function-local import, or ``alias.fn(...)``."""
    refs: List[str] = []
    if isinstance(node, ast.ImportFrom) and node.module and not node.level:
        refs.append(node.module)
    elif isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute):
        base = node.func.value
        origin = mod.imports.get(base.id) if isinstance(base, ast.Name) else None
        if origin:
            refs.append(origin[0] if origin[1] is None else origin[0] + "." + origin[1])
    return [
        r for r in refs
        if r.startswith(_BASH_PKG + ".")
        and r != _SHARED_CHECKS
        and not r.rsplit(".", 1)[-1].startswith("_")
    ]


def _fn_refs(fn: object, own_module: str) -> Tuple[List[str], List[str]]:
    """(guard-module dotted names, check-function names) a registered zero-arg closure references."""
    if not isinstance(fn, types.FunctionType):
        return [], []
    checks: List[str] = []
    modules: List[str] = []
    candidates: List[object] = []
    globs = fn.__globals__
    for ins in dis.get_instructions(fn.__code__):
        if ins.opname in ("LOAD_ATTR", "LOAD_METHOD", "LOAD_GLOBAL"):
            name = str(ins.argval)
            if re.match(r"_?check_", name) and name not in checks:
                checks.append(name)
            if ins.opname == "LOAD_GLOBAL" and globs.get(name) is not None:
                candidates.append(globs[name])
    for cell in fn.__closure__ or ():
        try:
            candidates.append(cell.cell_contents)
        except ValueError:
            continue
    for obj in candidates:
        dotted = obj.__name__ if isinstance(obj, types.ModuleType) else getattr(obj, "__module__", None)
        if isinstance(obj, types.FunctionType) and dotted == own_module and obj is not fn:
            sub_modules, sub_checks = _fn_refs(obj, own_module)
            modules.extend(m for m in sub_modules if m not in modules)
            checks.extend(c for c in sub_checks if c not in checks)
        elif isinstance(obj, (types.FunctionType, types.ModuleType)):
            if dotted and dotted != own_module and dotted.startswith("coordinator_core.") and dotted not in modules:
                modules.append(dotted)
    return modules, checks


@dataclass
class _Guard:
    key: str
    bash: Optional[object] = None
    bash_env: FrozenSet[str] = frozenset()
    bash_doc: str = ""
    write_module: Optional[str] = None
    write_env: FrozenSet[str] = frozenset()
    write_doc: str = ""


def _scan_module(dotted: str) -> Tuple[Set[str], str]:
    mod = _load_mod(dotted)
    if mod is None:
        return set(), ""
    env = _env_vars(mod.tree, mod)
    for module, _orig in mod.imports.values():
        if module.rsplit(".", 1)[-1].endswith("_contract"):
            contract = _load_mod(module)
            if contract is not None:
                env |= _env_vars(contract.tree, contract)
    return env, _first_line(ast.get_docstring(mod.tree))


def _collect() -> Dict[str, _Guard]:
    from coordinator_core.bash_guards import dispatch as _dispatch
    from coordinator_core.bash_guards.roster import guard_roster
    from coordinator_core.write_guards import engine as _engine
    import tempfile

    chain = _dispatch._build_guard_chain(
        cmd="echo coordinator-guard-roster-probe",
        session_id="guard-roster-probe",
        cwd=tempfile.gettempdir(),
        payload={"tool_name": "Bash", "tool_input": {"command": "echo x"}},
        policy_file=None,
        host_is_windows=None,
    )
    fns = {e.name: e.fn for e in chain}

    guards: Dict[str, _Guard] = {}
    for entry in guard_roster():
        g = guards.setdefault(route_key(entry.id), _Guard(route_key(entry.id)))
        g.bash = entry
        script_mod = _BASH_PKG.rsplit(".", 1)[0] + "." + entry.script[:-3].replace("/", ".")
        refs, checks = _fn_refs(fns.get(entry.id), _dispatch.__name__)
        scan = [m for m in [script_mod] + refs if m != _SHARED_CHECKS and not m.rsplit(".", 1)[-1].startswith("_")]
        env: Set[str] = set()
        doc = ""
        for dotted in dict.fromkeys(scan):
            e, d = _scan_module(dotted)
            env |= e
            doc = doc or d
        if _SHARED_CHECKS in refs or script_mod == _SHARED_CHECKS:
            e, d = _closure_env(checks)
            env |= e
            doc = d or doc or (("check function %s" % checks[0]) if checks else "")
        if not doc:
            doc = _scan_module(script_mod)[1]
        g.bash_env, g.bash_doc = frozenset(env), doc

    loaded, failed = _engine.discover_guard_names()
    if failed:
        raise RuntimeError("write guard modules failed to import: %s" % ", ".join(sorted(failed)))
    for name in loaded:
        key = route_key(name.replace("_", "-"))
        g = guards.setdefault(key, _Guard(key))
        g.write_module = "coordinator_core.write_guards." + name
        env, doc = _scan_module(g.write_module)
        g.write_env, g.write_doc = frozenset(env), doc
    return guards


def _section_stem(g: _Guard) -> str:
    if g.bash is not None:
        return "bash-" + g.bash.band
    return "write-" + g.key[len("gr:"):].split("-")[0]


def _render_entry(g: _Guard, grantable: FrozenSet[str], advisory_sentinel: FrozenSet[str]) -> str:
    lines = ["## " + g.key, ""]
    name = g.key[len("gr:"):]
    if g.bash is not None:
        b = g.bash
        mode = "fail-closed" if b.fail_closed else "fail-open"
        lines.append("- Bash: `coordinator_core/%s` (band %s, %s)" % (b.script, b.band, mode))
    if g.write_module is not None:
        lines.append("- Write: `%s.py`" % g.write_module.replace(".", "/"))
    lines.append("- Purpose: %s" % ((g.bash_doc if g.bash is not None else "") or g.write_doc or "(no docstring)"))
    env = sorted(g.bash_env | g.write_env)
    lines.append("- Override: %s" % (", ".join("`%s`" % v for v in env) if env else "none found in the module"))
    if g.bash is not None:
        chans = []
        if g.bash.fail_closed or g.bash.id in advisory_sentinel:
            chans.append("sentinel-eligible")
        if g.bash.id in grantable:
            chans.append("EM-grantable")
        lines.append("- Channels: %s" % (", ".join(chans) if chans else "none"))
    else:
        lines.append("- Channels: write plane; mechanics in guard-override-keys.md")
    return "\n".join(lines) + "\n"


def render_folder() -> Dict[str, str]:
    """Return ``{filename: text}`` for the whole folder; pure function of the live rosters."""
    from coordinator_core.bash_guards import dispatch as _dispatch
    from coordinator_core.session import em_guard_grant as _grant

    guards = _collect()
    grantable = frozenset(_grant._GRANTABLE_GUARDS)
    advisory = frozenset(_dispatch._SENTINEL_ELIGIBLE_ADVISORY_GUARDS)

    by_stem: Dict[str, List[str]] = {}
    for key in sorted(guards):
        by_stem.setdefault(_section_stem(guards[key]), []).append(key)

    files: Dict[str, str] = {}
    key_to_file: Dict[str, str] = {}
    for stem in sorted(by_stem):
        parts: List[List[str]] = []
        current: List[str] = []
        used = 2
        for key in by_stem[stem]:
            text = _render_entry(guards[key], grantable, advisory)
            need = len(text.splitlines()) + 1
            if current and used + need > _MAX_SECTION_LINES:
                parts.append(current)
                current, used = [], 2
            current.append(key)
            used += need
        parts.append(current)
        for i, keys in enumerate(parts, 1):
            fname = "%s.md" % stem if len(parts) == 1 else "%s-%d.md" % (stem, i)
            body = "\n".join(_render_entry(guards[k], grantable, advisory) for k in keys)
            files[fname] = "# Guard routes: %s\n\n%s" % (fname[:-3], body)
            for k in keys:
                key_to_file[k] = fname

    rows = "".join("| %s | %s |\n" % (k, key_to_file[k]) for k in sorted(key_to_file))
    files[ROUTES_INDEX] = "%s\n| Key | Section |\n|---|---|\n%s" % (_README_HEADER, rows)
    return files


def _folder() -> Path:
    return _REPO_ROOT / ROUTES_DIR


def differing_files(files: Optional[Dict[str, str]] = None) -> List[str]:
    """Sorted names whose on-disk bytes differ from the build (missing, stale or changed)."""
    built = render_folder() if files is None else files
    folder = _folder()
    on_disk = {p.name for p in folder.glob("*.md")} if folder.is_dir() else set()
    bad = set(on_disk ^ set(built))
    for name in set(built) & on_disk:
        if (folder / name).read_bytes().replace(b"\r\n", b"\n") != built[name].encode("utf-8"):
            bad.add(name)
    return sorted(bad)


def write_folder() -> List[str]:
    files = render_folder()
    folder = _folder()
    folder.mkdir(parents=True, exist_ok=True)
    for stale in folder.glob("*.md"):
        if stale.name not in files:
            stale.unlink()
    for name, text in files.items():
        atomic_write_bytes(folder / name, text.encode("utf-8"))
    return sorted(files)


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="regenerate the folder")
    mode.add_argument("--check", action="store_true", help="exit 1 and name files that differ")
    args = ap.parse_args(argv)
    if args.write:
        names = write_folder()
        print("wrote %d files under %s" % (len(names), ROUTES_DIR))
        return 0
    bad = differing_files()
    for name in bad:
        print(name)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
