# A stable, obviously-fake coordinator_root_path used across every fixture
# file — any fixed string works since the port-only tests call
# render_project_tracker.render() directly with a caller-supplied
# coordinator_root_path.
_FAKE_ROOT = "/fake/coordinator/root"


def _write_store(root: Path, coordinator_root_path: str) -> None:
    """Write a representative workstream store: two workstreams, mixed
    statuses, a superseded event, an orphan-deliverable event, and a
    quoted-scalar edge case — exercising fold, render-order, and
    union-tolerance in one fixture."""
    ws_dir = root / "state" / "workstreams"
    events_dir = ws_dir / "events"
    ws_dir.mkdir(parents=True, exist_ok=True)
    events_dir.mkdir(parents=True, exist_ok=True)

    (ws_dir / "wks-alpha.yaml").write_text(
        textwrap.dedent(f"""\
            workstream_id: "wks-alpha"
            title: "Alpha: quoting, commas"
            created: "2026-07-01"
            coordinator_root_path: "{coordinator_root_path}"
            specs:
              - "docs/plans/alpha.md"
            deliverables:
              - text: "Ship the thing"
              - text: "Write the docs"
        """),
        encoding="utf-8",
    )
    (ws_dir / "wks-beta.yaml").write_text(
        textwrap.dedent(f"""\
            workstream_id: "wks-beta"
            title: "Beta workstream"
            created: "2026-06-15"
            coordinator_root_path: "{coordinator_root_path}"
            deliverables:
              - text: "Only deliverable"
        """),
        encoding="utf-8",
    )

    # status: in_progress (seq 1) -> archived (seq 2) for wks-alpha.
    (events_dir / "2026-07-01-wks-alpha-session-a.yaml").write_text(
        textwrap.dedent(f"""\
            workstream: "wks-alpha"
            field: "status"
            sequence: 1
            session: "session-a"
            value: "in_progress"
            coordinator_root_path: "{coordinator_root_path}"
        """),
        encoding="utf-8",
    )
    (events_dir / "2026-07-02-wks-alpha-session-b.yaml").write_text(
        textwrap.dedent(f"""\
            workstream: "wks-alpha"
            field: "status"
            sequence: 2
            session: "session-b"
            value: "archived"
            coordinator_root_path: "{coordinator_root_path}"
        """),
        encoding="utf-8",
    )
    # A retracted event: sequence 3 but superseded by session-b's own
    # correction pointer — must NOT win the fold despite higher sequence
    # being the normal tiebreak (retraction beats sequence per fold rule).
    (events_dir / "2026-07-03-wks-alpha-session-c.yaml").write_text(
        textwrap.dedent(f"""\
            workstream: "wks-alpha"
            field: "status"
            sequence: 3
            session: "session-c"
            value: "in_progress"
            coordinator_root_path: "{coordinator_root_path}"
        """),
        encoding="utf-8",
    )
    (events_dir / "2026-07-04-wks-alpha-session-d.yaml").write_text(
        textwrap.dedent(f"""\
            workstream: "wks-alpha"
            field: "status"
            sequence: 4
            session: "session-d"
            value: "archived"
            supersedes: "session-c"
            coordinator_root_path: "{coordinator_root_path}"
        """),
        encoding="utf-8",
    )
    # deliverable[0].done for wks-alpha.
    (events_dir / "2026-07-01-wks-alpha-session-e.yaml").write_text(
        textwrap.dedent(f"""\
            workstream: "wks-alpha"
            field: "deliverable[0].done"
            sequence: 1
            session: "session-e"
            value: "true"
            coordinator_root_path: "{coordinator_root_path}"
        """),
        encoding="utf-8",
    )
    # orphan deliverable event on wks-beta (index 3, only 1 defined) —
    # union-tolerance path.
    (events_dir / "2026-07-05-wks-beta-session-f.yaml").write_text(
        textwrap.dedent(f"""\
            workstream: "wks-beta"
            field: "deliverable[3].done"
            sequence: 1
            session: "session-f"
            value: "true"
            coordinator_root_path: "{coordinator_root_path}"
        """),
        encoding="utf-8",
    )
    # status for wks-beta, active.
    (events_dir / "2026-06-15-wks-beta-session-g.yaml").write_text(
        textwrap.dedent(f"""\
            workstream: "wks-beta"
            field: "status"
            sequence: 1
            session: "session-g"
            value: "active"
            coordinator_root_path: "{coordinator_root_path}"
        """),
        encoding="utf-8",
    )
    # A different-tenant record that must be filtered OUT by the
    # coordinator_root_path discriminator (dual-tenant filter, AC9).
    (ws_dir / "wks-other-tenant.yaml").write_text(
        textwrap.dedent("""\
            workstream_id: "wks-other-tenant"
            title: "Should never render"
            created: "2020-01-01"
            coordinator_root_path: "/some/other/tenant/root"
        """),
        encoding="utf-8",
    )


