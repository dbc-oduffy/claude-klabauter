# ---------------------------------------------------------------------------
# Validator/renderer differential test — locks schema_validate (validate +
# parse) and the renderer's own parse path (_load_store_record) to agreeing
# on ONE deliverables encoding. The original defect (pre-C1/C8) was two
# hand-rolled YAML readers with complementary, non-overlapping subsets — the
# validator's took block-maps and rejected flow-maps, the renderer's was the
# exact inverse — so no single deliverables encoding satisfied both. This
# test feeds one fixture store through both readers and asserts they agree
# on the accept case and both reject the retired flow-map form, each in its
# own idiom (validate() reports {"ok": False, ...}; the renderer raises
# _RetiredFlowMapEncodingError) — closing off silent re-divergence in either
# direction.
# ---------------------------------------------------------------------------

from coordinator_core.frontmatter import schema_validate as sv  # noqa: E402

_BLOCK_MAP_STORE_TEXT = textwrap.dedent(f"""\
    workstream_id: "wks-differential"
    title: "Differential parity workstream"
    created: "2026-07-18"
    coordinator_root_path: "{_FAKE_ROOT}"
    specs:
      - "docs/plans/differential.md"
    deliverables:
      - text: "Ship the thing"
      - text: "Write the docs"
""")

_FLOW_MAP_STORE_TEXT = textwrap.dedent(f"""\
    workstream_id: "wks-differential-flow"
    title: "Differential parity workstream (flow-map)"
    created: "2026-07-18"
    coordinator_root_path: "{_FAKE_ROOT}"
    deliverables:
      - {{text: "Ship the thing"}}
      - {{text: "Write the docs"}}
""")


def test_validator_and_renderer_agree_on_block_map_deliverables(tmp_path):
    path = tmp_path / "wks-differential.yaml"
    path.write_text(_BLOCK_MAP_STORE_TEXT, encoding="utf-8")

    validator_parsed = sv.parse_yaml(_BLOCK_MAP_STORE_TEXT)
    validator_result = sv.validate("workstream", validator_parsed)
    assert validator_result == {"ok": True}, validator_result

    schema = rpt._cached_schema(rpt._DEFINITION_SCHEMA_FILE)
    renderer_parsed = rpt._load_store_record(str(path), schema)

    assert renderer_parsed["deliverables"] == validator_parsed["deliverables"]
    assert renderer_parsed["deliverables"] == [
        {"text": "Ship the thing"},
        {"text": "Write the docs"},
    ]


def test_flow_map_deliverables_rejected_by_both_readers_in_own_idiom(tmp_path):
    path = tmp_path / "wks-differential-flow.yaml"
    path.write_text(_FLOW_MAP_STORE_TEXT, encoding="utf-8")

    validator_parsed = sv.parse_yaml(_FLOW_MAP_STORE_TEXT)
    validator_result = sv.validate("workstream", validator_parsed)
    assert validator_result["ok"] is False
    assert any(
        "deliverables" in err["field"] for err in validator_result["errors"]
    )

    schema = rpt._cached_schema(rpt._DEFINITION_SCHEMA_FILE)
    with pytest.raises(rpt._RetiredFlowMapEncodingError):
        rpt._load_store_record(str(path), schema)


