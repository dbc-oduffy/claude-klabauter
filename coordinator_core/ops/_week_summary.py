"""The one WEEK-SUMMARY.md writer, shared by changelog.backfill_gaps and workweek-complete-close."""

from __future__ import annotations

import datetime
import os
import re
import tempfile
from pathlib import Path
from typing import Dict, List, Optional, Tuple

_ARCHIVED_DAY_RE = re.compile(r"^(\d{4}-\d{2}-\d{2})(?:-[^/\\]+)?\.md$")


def _replace_atomically(path: Path, content: str) -> None:
    fd, tmp = tempfile.mkstemp(dir=str(path.parent), suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="") as fh:
            fh.write(content)
        os.replace(tmp, path)
    except Exception:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


def write_week_summary(
    archive_dest: Path,
    week_starting: str,
    *,
    planned: Tuple[str, ...] = (),
    dry_run: bool = False,
) -> Optional[Path]:
    """Create or extend `<archive_dest>/WEEK-SUMMARY.md` from the archived day files.

    Returns the path when written (under `dry_run`, when it would be), None when
    nothing changes. `planned` names day files a dry run would add. An existing
    file is never rewritten: only day bullets it lacks are appended. No narrative
    or Strategic Review is fabricated.
    trap: a day file may carry a suffix (`YYYY-MM-DD-<host>-backfill.md`, the
    backfill shape); the mover archives those, so the days list must count them too.
    """
    names = sorted({f.name for f in archive_dest.glob("*.md")} | set(planned))
    files_by_day: Dict[str, List[str]] = {}
    for name in names:
        if m := _ARCHIVED_DAY_RE.match(name):
            files_by_day.setdefault(m.group(1), []).append(name)
    days = sorted(files_by_day)
    if not days:
        return None
    path = archive_dest / "WEEK-SUMMARY.md"
    bullets = {
        d: f"- **{d}** — " + ", ".join(f"[{n}]({n})" for n in files_by_day[d]) for d in days
    }
    if path.exists():
        text = path.read_text(encoding="utf-8")
        missing = [b for d, b in bullets.items() if f"**{d}**" not in text]
        if not missing:
            return None
        if dry_run:
            return path
        if "## Days" not in text:
            text = text.rstrip("\n") + "\n\n## Days\n"
        _replace_atomically(path, text.rstrip("\n") + "\n" + "\n".join(missing) + "\n")
        return path
    if dry_run:
        return path
    start = datetime.date.fromisoformat(week_starting)
    iso = start.isocalendar()
    end = start + datetime.timedelta(days=6)
    archive_dest.mkdir(parents=True, exist_ok=True)
    _replace_atomically(
        path,
        "---\nrollup_schema: 1\ngrain: week\n"
        f"period: {iso[0]}-W{iso[1]:02d}\nweek_start: {start.isoformat()}\n"
        f"week_end: {end.isoformat()}\n"
        f"days: [{', '.join(days)}]\nbackfilled: true\nnarrative: none\n---\n\n"
        f"# Week Summary — {start.isoformat()} .. {end.isoformat()}\n\n"
        "> Generated by workweek-complete-close archive --week-only; no narrative authored.\n\n"
        "## Days\n\n" + "\n".join(bullets.values()) + "\n",
    )
    return path
