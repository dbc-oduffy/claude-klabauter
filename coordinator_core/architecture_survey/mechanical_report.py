"""Deterministic atlas mechanical-layer report (schema atlas-mechanical-layer v1); no model.

Joins the citation checker's dead-path rows with `structure.json`'s file-index and edges needs,
diffs both against the atlas artifacts as committed, and lists a page in `pages_changed` only for
genuine drift: a dead path on it, an added/removed file in its system, or a changed matrix cell
touching its system. Generated pages are regenerated by `render`, never handed to a narrative agent.
A page with no committed baseline (never rendered) yields no delta rather than "everything added".
"""
from __future__ import annotations

import argparse
import copy
import functools
import importlib.util
import json
import re
import sys
from datetime import date
from pathlib import Path
from typing import Any

from coordinator_core.architecture_survey import render, structure as structure_mod
from coordinator_core.distill.prompt_tier import estimate_tokens

SCHEMA = "atlas-mechanical-layer"
SCHEMA_VERSION = 1
BRIEF_CLAUSE = "minimal edit, high-level only, no history"
PREVIEW_CAP_BYTES = 1200
TOKEN_BASIS = "estimate_tokens(utf-8 bytes of compact page_briefs JSON)"
GENERATED_PREFIX = "Generated by `coordinator_core.architecture_survey.render`"
DEAD_KINDS = ("unresolved-file", "misrooted-file")
CHECKER_REL = Path("coordinator") / "bin" / "atlas-citation-check.py"
SYSTEMS_DIR = "systems"
_CITED_RE = re.compile(r"`([^`]+)`")
_ARROW_RE = re.compile(r"^(?P<path>.+?) -> (?P<system>\S+)$")
_OTHER_REPO_RE = re.compile(r"\b(?:DoE-side|DoE's|cross-repo)\b", re.IGNORECASE)


def _atlas_rel() -> str:
    return render.ATLAS_DIR.as_posix()


def load_checker(repo_root: Path) -> Any:
    """Import the hyphen-named checker script by path (it is a CLI, not a package module)."""
    path = repo_root / CHECKER_REL
    spec = importlib.util.spec_from_file_location("atlas_citation_check", path)
    if spec is None or spec.loader is None:
        raise FileNotFoundError(str(path))
    module = importlib.util.module_from_spec(spec)
    sys.modules["atlas_citation_check"] = module
    spec.loader.exec_module(module)
    return module


def dead_path_rows(report: Any) -> list[dict[str, Any]]:
    """The checker's dead-path findings as report rows; other finding kinds are not dead paths."""
    rows = []
    for f in report.findings:
        if f.kind not in DEAD_KINDS:
            continue
        match = _CITED_RE.search(f.detail)
        rows.append({"cls": f.kind, "page": f.page, "line": f.line,
                     "cited": match.group(1) if match else f.detail, "target": None})
    return rows


@functools.cache
def _historical_dirs() -> tuple[str, ...]:
    """The checker's own historical-page dirs, so the rule has one source."""
    module = sys.modules.get("atlas_citation_check") or load_checker(Path(__file__).resolve().parents[2])
    return module._HISTORICAL_PAGE_DIRS


def _historical(page: str) -> bool:
    return any(f"/{d}/" in f"/{page}" for d in _historical_dirs())


def other_repo_cite(root: Path, row: dict[str, Any]) -> bool:
    """True when the prose on the cite's line or the next marks it as another repo's file (`DoE-side`, `cross-repo`)."""
    try:
        lines = (root / row["page"]).read_text(encoding="utf-8").splitlines()
    except OSError:
        return False
    at = (row["line"] or 0) - 1
    if at < 0 or at >= len(lines):
        return False
    return _OTHER_REPO_RE.search(" ".join(lines[at:at + 2])) is not None


def _baseline_file_rows(text: str | None) -> set[tuple[str, str]] | None:
    """`path -> system` rows of the committed generated block; None when no block was ever rendered."""
    if text is None:
        return None
    block = render._BLOCK_RE.search(text)
    if block is None:
        return None
    rows = set()
    for line in block.group(0).splitlines():
        m = _ARROW_RE.match(line.strip())
        if m:
            rows.add((m.group("path"), m.group("system")))
    return rows


def _baseline_matrix(text: str | None) -> dict[tuple[str, str], int] | None:
    """Off-diagonal cells of the committed generated matrix; None when it is not render's output."""
    if text is None or GENERATED_PREFIX not in text:
        return None
    header: list[str] | None = None
    cells: dict[tuple[str, str], int] = {}
    for line in text.splitlines():
        if not line.startswith("|"):
            continue
        cols = [c.strip() for c in line.strip().strip("|").split("|")]
        if header is None:
            header = cols[1:]
            continue
        if set(cols[0]) <= set("-") or len(cols) != len(header) + 1:
            continue
        for col, cell in zip(header, cols[1:]):
            if cell.isdigit():
                cells[(cols[0], col)] = int(cell)
    return cells if header is not None else None


def _fresh_matrix(edges_payload: Any) -> dict[tuple[str, str], int]:
    data = render._data(edges_payload) or {}
    weights: dict[tuple[str, str], int] = {}
    for edge in (data.get("edges", []) if isinstance(data, dict) else []):
        key = (edge["from_system"], edge["to_system"])
        weights[key] = weights.get(key, 0) + edge["weight"]
    return weights


def _matrix_delta(fresh: dict[tuple[str, str], int], base: dict[tuple[str, str], int]) -> list[dict[str, Any]]:
    """Changed cells, zero treated as absent so a missing cell and an explicit 0 do not differ."""
    changed = []
    for key in sorted(set(fresh) | set(base)):
        before, after = base.get(key, 0), fresh.get(key, 0)
        if before != after:
            changed.append({"from": key[0], "to": key[1], "before": before, "after": after})
    return changed


def _preview(path: Path) -> str:
    """The page's head, at most PREVIEW_CAP_BYTES of UTF-8; a split trailing character is dropped."""
    with path.open("rb") as fh:
        head = fh.read(PREVIEW_CAP_BYTES)
    return head.decode("utf-8", errors="ignore")


def _system_of(page: str) -> str | None:
    prefix = f"{_atlas_rel()}/{SYSTEMS_DIR}/"
    return page[len(prefix):-len(".md")] if page.startswith(prefix) and page.endswith(".md") else None


def _page_brief(root: Path, page: str, reasons: list[str], live_dead: list[dict[str, Any]],
                file_index: dict[str, Any], matrix: dict[str, Any]) -> dict[str, Any]:
    """One drifted page's payload for the narrative step: reasons, its own deltas, a capped preview."""
    system = _system_of(page)

    def rows_of(key: str) -> list[Any]:
        return [r for r in (file_index[key] or []) if r[1] == system]

    return {
        "reasons": sorted(set(reasons)),
        "brief": BRIEF_CLAUSE,
        "dead_paths": [r for r in live_dead if r["page"] == page],
        "file_index": {"added": rows_of("added"), "removed": rows_of("removed")},
        "matrix_cells": [c for c in matrix["changed_cells"] if system in (c["from"], c["to"])],
        "preview": _preview(root / page),
    }


def narrative_tokens(page_briefs: dict[str, Any]) -> dict[str, Any]:
    """Measured size of the payload handed to the narrative step, in bytes and estimated tokens."""
    size = len(json.dumps(page_briefs, sort_keys=True, separators=(",", ":")).encode("utf-8"))
    return {"narrative_payload": estimate_tokens(size), "bytes": size, "pages": len(page_briefs), "basis": TOKEN_BASIS}


def _read(path: Path) -> str | None:
    return path.read_text(encoding="utf-8") if path.is_file() else None


def build_report(
    repo_root: Path | str, structure: dict[str, Any], dead_rows: list[dict[str, Any]], *,
    extra_findings: int = 0,
) -> dict[str, Any]:
    """Assemble the v1 report from `structure` (needs) and checker `dead_rows`; pure over disk reads of the atlas."""
    root = Path(repo_root)
    foreign = [r for r in dead_rows if other_repo_cite(root, r)]
    dead_rows = [r for r in dead_rows if r not in foreign]
    atlas = root / render.ATLAS_DIR
    needs = structure["needs"]
    reasons: dict[str, list[str]] = {}

    def flag(page: str, why: str) -> None:
        reasons.setdefault(page, []).append(why)

    live_dead = [r for r in dead_rows if not _historical(r["page"])]
    matrix_text = _read(atlas / render.MATRIX_NAME)
    matrix_page = f"{_atlas_rel()}/{render.MATRIX_NAME}"
    matrix_generated = matrix_text is not None and GENERATED_PREFIX in matrix_text
    file_index_page = f"{_atlas_rel()}/{render.FILE_INDEX_NAME}"
    file_index_generated = _baseline_file_rows(_read(atlas / render.FILE_INDEX_NAME)) is not None
    for row in live_dead:
        if (row["page"] == matrix_page and matrix_generated) or (
                row["page"] == file_index_page and file_index_generated):
            continue
        flag(row["page"], f"dead-path: `{row['cited']}`")

    legs: dict[str, dict[str, Any]] = {
        "dead-paths": {"status": "ran", "producer": "atlas-citation-check",
                       "detail": f"{len(dead_rows)} dead paths, {len(live_dead)} off historical pages; "
                                 f"{extra_findings} further non-dead-path findings; {len(foreign)} other-repo cites excluded"},
        "rename-targets": {"status": "not-run", "producer": None,
                           "detail": "advisory lookup, not spawned: dead_paths target stays null"},
    }

    fi_need, ed_need = needs["file-index"], needs["edges"]
    file_index: dict[str, Any] = {"added": None, "removed": None, "systems_touched": []}
    if fi_need["covered"]:
        fresh_rows = {(r["path"], r["system"]) for r in render._data(fi_need["payload"]) or []}
        base_rows = _baseline_file_rows(_read(atlas / render.FILE_INDEX_NAME))
        if base_rows is None:
            legs["file-index"] = {"status": "ran", "producer": structure_mod.FILE_INDEX_SOURCE,
                                  "detail": f"{len(fresh_rows)} rows; no committed baseline, no delta"}
        else:
            added, removed = sorted(fresh_rows - base_rows), sorted(base_rows - fresh_rows)
            file_index.update(added=[list(r) for r in added], removed=[list(r) for r in removed])
            touched = sorted({s for _p, s in added} | {s for _p, s in removed})
            file_index["systems_touched"] = touched
            for system in touched:
                flag(f"{_atlas_rel()}/{SYSTEMS_DIR}/{system}.md", f"file-index delta in system `{system}`")
            legs["file-index"] = {"status": "ran", "producer": structure_mod.FILE_INDEX_SOURCE,
                                  "detail": f"{len(fresh_rows)} rows; +{len(added)} -{len(removed)}"}
    else:
        legs["file-index"] = {"status": "uncovered", "producer": None, "detail": str(fi_need["reason"])}

    matrix: dict[str, Any] = {"changed_cells": [], "systems_touched": []}
    if ed_need["covered"]:
        base = _baseline_matrix(matrix_text)
        fresh = _fresh_matrix(ed_need["payload"])
        if base is None:
            legs["connectivity-matrix"] = {"status": "ran", "producer": "project_architecture_graph",
                                           "detail": f"{len(fresh)} edges; no committed baseline, no delta"}
        else:
            cells = _matrix_delta(fresh, base)
            matrix["changed_cells"] = cells
            matrix["systems_touched"] = sorted({c["from"] for c in cells} | {c["to"] for c in cells})
            for c in cells:
                for system in (c["from"], c["to"]):
                    flag(f"{_atlas_rel()}/{SYSTEMS_DIR}/{system}.md", f"matrix cell {c['from']}->{c['to']}")
            legs["connectivity-matrix"] = {"status": "ran", "producer": "project_architecture_graph",
                                           "detail": f"{len(fresh)} edges; {len(cells)} cells changed"}
    else:
        legs["connectivity-matrix"] = {"status": "uncovered", "producer": None, "detail": str(ed_need["reason"])}

    pages = sorted(p for p in reasons if (root / p).is_file())
    absent = sorted(set(reasons) - set(pages))
    legs["pages-changed"] = {
        "status": "ran", "producer": "drift gate",
        "detail": f"{len(pages)} pages with genuine drift" + (f"; {len(absent)} drifted systems have no page" if absent else ""),
    }
    page_briefs = {p: _page_brief(root, p, reasons[p], live_dead, file_index, matrix) for p in pages}
    return {
        "schema": SCHEMA, "schema_version": SCHEMA_VERSION, "legs": legs,
        "dead_paths": dead_rows, "file_index": file_index, "connectivity_matrix": matrix,
        "pages_changed": pages,
        "page_briefs": page_briefs, "tokens": narrative_tokens(page_briefs),
        "systems_without_page": absent,
    }


def _atlas_pages(root: Path) -> list[str]:
    return sorted(p.relative_to(root).as_posix() for p in (root / render.ATLAS_DIR).rglob("*.md"))


def _fetch_structure(root: Path, run_dir: Path) -> dict[str, Any]:
    costs = json.loads((Path(structure_mod.__file__).parent / "rag_read_costs.json").read_text(encoding="utf-8"))
    pages = _atlas_pages(root)
    try:
        return structure_mod.fetch(root, run_dir, pages, costs=costs)
    except structure_mod.StructureUnavailable as exc:
        local = copy.deepcopy(costs)
        local["needs"]["edges"]["fetch"] = False
        local["needs"]["dead-paths"].pop("batched_door", None)
        fallback = structure_mod.fetch(root, run_dir, pages, costs=local)
        edges = fallback["needs"]["edges"]
        if not edges["covered"]:
            edges["reason"] = f"rag-unavailable, edges not fetched: {exc}"
        return fallback


def produce(repo_root: Path | str, out: Path | str | None = None, *, today: date | None = None,
            structure: dict[str, Any] | None = None) -> dict[str, Any]:
    """Default run: checker rows + a fresh structure fetch -> report written to `out` (default scratch/atlas-mechanical)."""
    root = Path(repo_root).resolve()
    stamp = (today or date.today()).isoformat()
    base = root / "scratch" / "atlas-mechanical"
    checker = load_checker(root)
    check = checker.run(root, root / render.ATLAS_DIR)
    rows = dead_path_rows(check)
    if structure is None:
        structure = _fetch_structure(root, base / f"{stamp}-run")
    report = build_report(root, structure, rows, extra_findings=len(check.findings) - len(rows))
    target = Path(out) if out else base / f"{stamp}-report.json"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return report


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-root", default=".")
    parser.add_argument("--out", default=None)
    args = parser.parse_args(argv)
    report = produce(args.repo_root, args.out)
    tokens = report["tokens"]
    print(f"pages_changed={len(report['pages_changed'])} dead_paths={len(report['dead_paths'])} "
          f"tokens={tokens['narrative_payload']} ({tokens['bytes']} bytes, {tokens['pages']} pages)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
