"""Closed-set comment tags: only a leading `trap:`, `invariant:`, `external-constraint:` exempts an added comment."""
from __future__ import annotations

import pytest

from coordinator_core.commenting.added import added_comments
from coordinator_core.commenting.allow import TAGS, has_tag, is_allowed_comment

_PY = "src/mod.py"
_TS = "src/mod.ts"


def _py(comment: str) -> list:
    return added_comments(_PY, "x = 1\n", f"x = 1\n{comment}\ny = 2\n")


def _ts(comment: str) -> list:
    return added_comments(_TS, "const x = 1;\n", f"const x = 1;\n{comment}\nconst y = 2;\n")


def test_closed_set_is_exactly_three_tags():
    assert TAGS == ("trap", "invariant", "external-constraint")


@pytest.mark.parametrize(
    "text",
    [
        "# trap: x",
        "#trap: x",
        "#   invariant: x",
        "// invariant: x",
        "//external-constraint: x",
        "/* external-constraint: x */",
        "/** trap: x */",
    ],
)
def test_tagged_comment_has_tag_and_is_allowed(text):
    assert has_tag(text)
    assert is_allowed_comment(text)


@pytest.mark.parametrize(
    "text",
    [
        "# Trap: x",
        "# TRAP: x",
        "# note trap: x",
        "# because x",
        "# trap x",
        "# trap : x",
        "# invariants: x",
        "# external_constraint: x",
        "// Invariant: x",
        "/* note: external-constraint: x */",
    ],
)
def test_untagged_or_misspelled_comment_has_no_tag(text):
    assert not has_tag(text)
    assert not is_allowed_comment(text)


@pytest.mark.parametrize("comment", ["# trap: x", "# invariant: x", "# external-constraint: x"])
def test_added_python_tagged_comment_raises_nothing(comment):
    assert _py(comment) == []


@pytest.mark.parametrize("comment", ["// trap: x", "// invariant: x", "/* external-constraint: x */"])
def test_added_clike_tagged_comment_raises_nothing(comment):
    assert _ts(comment) == []


@pytest.mark.parametrize("comment", ["# Trap: x", "# note trap: x", "# because x"])
def test_added_python_untagged_comment_raises_one_finding(comment):
    found = _py(comment)
    assert len(found) == 1
    assert found[0].path == _PY
    assert found[0].text == comment


@pytest.mark.parametrize("comment", ["// Invariant: x", "// note trap: x", "/* because x */"])
def test_added_clike_untagged_comment_raises_one_finding(comment):
    assert len(_ts(comment)) == 1


@pytest.mark.parametrize(
    "header",
    ["# generated from the plan", "# generated by hand", "x = 'do not edit'", "# the generated file is fine"],
)
def test_agent_added_generated_looking_header_still_flags(header):
    assert len(added_comments("pkg/gen.py", "", f"{header}\nx = 1\n# more\n")) >= 1


@pytest.mark.parametrize("header", ["# Code generated by protoc. DO NOT EDIT.", "// @generated", "/* auto-generated */"])
def test_real_generated_header_silences_lint(header):
    suffix = ".py" if header.startswith("#") else ".ts"
    assert added_comments(f"pkg/gen{suffix}", "", f"{header}\nx = 1\n# more\n" if suffix == ".py" else f"{header}\nconst x = 1;\n// more\n") == []
